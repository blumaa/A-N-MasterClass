// Writes src/tokens/brandGraph.generated.ts from src/tokens/brand.css so TS code
// (contrast check, live preview) evaluates the exact aliases the browser does.
// Run: pnpm gen:brand. brandGraph.test.ts fails when the output is stale.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseBrandCss } from '../src/tokens/parseBrandCss.ts';

const tokens = join(dirname(fileURLToPath(import.meta.url)), '../src/tokens');
const graph = parseBrandCss(readFileSync(join(tokens, 'brand.css'), 'utf8'));

writeFileSync(
  join(tokens, 'brandGraph.generated.ts'),
  `// GENERATED by scripts/gen-brand-graph.mjs from brand.css. Do not edit; run pnpm gen:brand.
import type { BrandGraph } from './parseBrandCss';

export const BRAND_GRAPH: BrandGraph = ${JSON.stringify(graph, null, 2)};
`,
);
